#!/usr/bin/env python3
"""Create a dependency-free Worker file for Cloudflare's Dashboard editor."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]

def source(root=ROOT):
    model=(root/'web/model.mjs').read_text()
    portal=(root/'adapter/owner-page.mjs').read_text()
    worker=(root/'adapter/worker.mjs').read_text()
    for line in ["import {fromProvider,jobId,publicImageUrl} from '../web/model.mjs';", "import {OWNER_PAGE} from './owner-page.mjs';"]:
        if worker.count(line)!=1: raise ValueError('Adapter imports changed; update this small bundler before deployment.')
        worker=worker.replace(line,'')
    model=re.sub(r'^export (?=const |function )','',model,flags=re.M)
    portal=portal.replace('export const OWNER_PAGE','const OWNER_PAGE',1)
    if re.search(r'^import\s',model+portal+worker,flags=re.M): raise ValueError('Dashboard bundle must not depend on external modules.')
    return '// Generated by scripts/build_adapter.py. Edit source modules, then regenerate.\n// Contains no secrets. Paste this entire file into the Cloudflare Worker editor.\n'+model+'\n'+portal+'\n'+worker

if __name__=='__main__':
    (ROOT/'adapter/worker-dashboard.mjs').write_text(source())
    print('Built adapter/worker-dashboard.mjs (no credentials or deployment).')
